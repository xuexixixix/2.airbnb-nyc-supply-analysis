-- 房源生命周期：把全部房源按「评论活跃度」分成三档
--
-- 业务问题
--     前面的分析发现：44% 的房源「开门但没客」。
--     但这个说法太粗 —— 需要区分两种完全不同的情况：
--         ① 一直没生意           （房源本身有问题：位置差、定价高、信息烂）
--         ② 曾经有生意，后来没了   （平台/市场变化，或房东放弃经营）
--     这两种情况的运营对策完全相反，不能混为一谈。
--
-- 关键区分：两个"零"不是一回事
--     number_of_reviews_ltm = 0   →  最近 12 个月没评论   19,783 套（65.4%）
--     MAX(reviews.date) IS NULL   →  历史上从未有评论      8,559 套（28.3%）
--     差距 11,224 套 —— 这批就是"曾经有、后来没了"
--
-- ⚠️ 时间基准怎么选（容易错的地方）
--     不能用 NOW()（今天）当基准。原因两条：
--       ① 数据是 2026-06-14~06-23 抓的，距今已有数月
--       ② 平台的 number_of_reviews_ltm 是在【抓取那一刻】算的"近 12 个月"
--     用今天的日期当基准，会把口径和平台错开，算出来的"活跃数"对不上。
--     → 正确做法：用快照日期做基准。
--       这里取 MAX(last_scraped) = 2026-06-23（该列取值 06-14 ~ 06-23）
--
-- 结论
--     生命周期状态                房源数     占比
--     1. 从未有评论（僵尸）        8,559    28.3%
--     2. 活跃（近一年有评论）     10,419    34.4%
--     3. 沉寂（曾有评论，近一年无） 11,281    37.3%
--                               ─────────
--                                30,259   100%
--
--     🔴 关键发现：最大的那一档不是"从来没生意"，而是"曾经有、后来没了"。
--
--     这修正了 00_supply_overview.sql「44% 开门但没客」的表述 ——
--     那个说法暗示"这些房源一直没人要"，实际其中大半曾经经营过：
--         19,783 套近一年无评论
--            ├─  8,559 套  从来就没有过评论
--            └─ 11,281 套  曾经有评论，最近一年断了  ← 属于"流失"
--
--     业务含义完全不同：
--         僵尸（8,559）   → 房源本身可能有问题（位置/定价/信息质量）
--         沉寂（11,281）  → 房东曾证明过能做成生意，是可通过沟通挽回的
--         「流失」比「从未激活」更值得运营投入。
--
--     ⚠️ 口径偏差说明（必须写进报告）
--         本查询算出的"活跃"为 10,419 套，
--         而平台字段 number_of_reviews_ltm > 0 的为 10,476 套，差 57 套（0.19%）。
--         原因：本查询用「快照日期往前推 365 天」，
--         而平台的 ltm 口径可能按自然月、或按各房源各自的抓取日计算。
--         差异不影响结论，但须在报告中声明。

SELECT
    CASE
        -- 第一档：评论表里一条记录都找不到
        WHEN 最后评论日期 IS NULL
            THEN '1. 从未有评论（僵尸）'

        -- 第二档：最后一条评论在快照日期前 365 天之内
        WHEN 最后评论日期 >= DATE_SUB(
                 (SELECT MAX(last_scraped) FROM listings),
                 INTERVAL 365 DAY
             )
            THEN '2. 活跃（近一年有评论）'

        -- 第三档：曾经有评论，但近一年没有
        ELSE
             '3. 沉寂（曾有评论，近一年无）'

    END                                                            AS 生命周期状态,

    COUNT(*)                                                       AS 房源数,

    ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM listings), 1)   AS 占全部房源百分比

FROM (
    -- 子查询：把评论表收敛成「一行一房源」
    -- 不套这一层的话，一个房源有几条评论就会出几行，分组会算错
    SELECT
        l.id,
        MAX(r.date) AS 最后评论日期
    FROM listings l
    LEFT JOIN reviews r ON l.id = r.listing_id     -- 必须 LEFT：否则没评论的房源会整体消失
    GROUP BY l.id
) t
GROUP BY 生命周期状态
ORDER BY 生命周期状态;
