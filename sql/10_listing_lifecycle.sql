-- 房源生命周期：把全部房源按「评论活跃度」分成三档
--
-- 业务问题
--     前面的分析发现：44% 的房源「开门但没客」。
--     但这个说法太粗 —— 需要区分两种完全不同的情况：
--         ① 一直没生意           （房源本身有问题：位置差、定价高、信息烂）
--         ② 曾经有生意，后来没了   （平台/市场变化，或房东放弃经营）
--     这两种情况的运营对策完全相反，不能混为一谈。
--
-- 分类口径
--     僵尸 = number_of_reviews = 0         历史上从未有过任何评论
--     沉寂 = number_of_reviews > 0
--            且 number_of_reviews_ltm = 0   曾有评论，但近一年没有
--     活跃 = 其余
--
-- ⚠️ 为什么用单表字段，而不是 Join reviews 表
--     另一条路是 Join reviews 表，用 MAX(reviews.date) 自己按
--     「快照日往前 365 天」划界（见 sql/09_review_timeline.sql）。
--     两套口径的结果：
--         单表（本文件）：僵尸 8,559 · 沉寂 11,224 · 活跃 10,476
--         Join（sql/09）：僵尸 8,559 · 沉寂 11,281 · 活跃 10,419   差 57 套（0.19%）
--
--     选单表口径的理由：
--       1. number_of_reviews_ltm 是 Inside Airbnb【官方计算】的"近 12 个月"，
--          而 Join 口径是我们自己拿 365 天硬凑的 —— 官方字段更权威
--       2. 不需要 Join 1115 万行的日历表 / 99 万行的评论表，更快
--       3. 与 Power BI 看板和 matplotlib 图表保持一致，
--          同一个项目不能出现两套数字
--
--     僵尸一档两套算法完全一致（都是 8,559），差异只出现在沉寂/活跃的边界上。
--
-- 结论
--     生命周期状态                房源数     占比
--     1. 从未有评论（僵尸）        8,559    28.3%
--     2. 活跃（近一年有评论）     10,476    34.6%
--     3. 沉寂（曾有评论，近一年无） 11,224    37.1%
--                               ─────────
--                                30,259   100%
--
--     🔴 关键发现：最大的那一档不是"从来没生意"，而是"曾经有、后来没了"。
--
--     这修正了 00_supply_overview.sql「44% 开门但没客」的表述 ——
--     那个说法暗示"这些房源一直没人要"，实际其中大半曾经经营过：
--         19,783 套近一年无评论
--            ├─  8,559 套  从来就没有过评论
--            └─ 11,224 套  曾经有评论，最近一年断了  ← 属于"流失"
--
--     业务含义完全不同：
--         僵尸（8,559）   → 房源本身可能有问题（位置/定价/信息质量）
--         沉寂（11,224）  → 房东曾证明过能做成生意，是可通过沟通挽回的
--         「流失」比「从未激活」更值得运营投入。

SELECT
    CASE
        -- 第一档：历史累计评论数为 0，即从未有过任何评论
        WHEN number_of_reviews = 0
            THEN '1. 从未有评论（僵尸）'

        -- 第二档：有历史评论，但近 12 个月没有
        WHEN number_of_reviews_ltm = 0
            THEN '3. 沉寂（曾有评论，近一年无）'

        -- 第三档：近 12 个月有评论
        ELSE
             '2. 活跃（近一年有评论）'

    END                                                            AS 生命周期状态,

    COUNT(*)                                                       AS 房源数,

    ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM listings), 1)   AS 占全部房源百分比

FROM listings
GROUP BY 生命周期状态
ORDER BY 生命周期状态;
