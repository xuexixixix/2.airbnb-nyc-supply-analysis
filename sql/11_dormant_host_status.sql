-- 沉寂房源的房东，还在经营吗？
--
-- 业务问题
--     10_listing_lifecycle.sql 发现：11,224 套房源「曾经有评论、近一年断了」。
--     这是平台最大的一档（37.1%），比"从未有评论"的还多。
--
--     但"没有评论"有两种可能，运营对策完全相反：
--         ① 房东已经放弃 —— 房源关掉了，只是没下架
--         ② 房东还在营业 —— 门开着，但没客人来
--     ①要联系房东了解退出原因，②要解决曝光/定价/竞争力问题。
--
-- 方法
--     用 listings 表自带的 availability_365（未来 365 天中可订的天数）判断：
--         availability_365 > 0  → 仍在接客
--         availability_365 = 0  → 已停止接客
--
--     注：这个问题不需要 Join calendar 表（1115 万行）。
--         listings 里的 availability_365 就是同一个信息的聚合版本。
--         知道什么时候不用大表 —— 也是一种能力。
--
-- 口径
--     与 sql/10 保持一致，用单表字段：
--         僵尸 = number_of_reviews = 0
--         沉寂 = number_of_reviews > 0 且 number_of_reviews_ltm = 0
--         活跃 = 其余
--
-- 结论
--     生命周期状态              接客状态        房源数
--     ────────────────────────────────────────────────
--     1. 僵尸（从未有评论）     仍在接客         7,246
--     1. 僵尸（从未有评论）     已停止接客       1,313   → 15.3%
--     ────────────────────────────────────────────────
--     2. 活跃（近一年有评论）   仍在接客        10,136
--     2. 活跃（近一年有评论）   已停止接客         340   →  3.2%
--     ────────────────────────────────────────────────
--     3. 沉寂（曾有评论，近一年无）仍在接客       6,086
--     3. 沉寂（曾有评论，近一年无）已停止接客     5,138   → 45.8%
--
--     关店率对比：
--         活跃  3.2%  ▏
--         僵尸 15.3%  ▎▎
--         沉寂 45.8%  ██████████████   ← 断崖
--
--     🔴 关键结论：沉寂房源中将近一半（5,138 套）的房东已停止接客。
--     这个比例远高于其他两档 —— 说明"房东退出"是真实发生的，
--     且高度集中在「沉寂」这一档。
--
--     三档房源的完整画像：
--         活跃  10,476  96.8% 还开着   正常经营
--         僵尸   8,559  84.7% 还开着   门开着但从没来过客人（房东仍抱着希望）
--         沉寂  11,224  45.8% 已关门   一半硬撑、一半已退出
--
--     「僵尸」和「沉寂」是两种不同的病：
--         僵尸 → 房源本身的问题（位置差 / 定价高 / 信息质量低）
--         沉寂 → 真实的房东流失，其中 5,138 套已退出
--
--     运营优先级：那 5,138 套已退出的房源最该被联系 ——
--     他们曾经做成过生意（有历史评论），现在关门了。
--     问一句"为什么退出"，就能知道平台真正的问题出在哪。

SELECT
    CASE
        WHEN number_of_reviews = 0     THEN '1. 僵尸（从未有评论）'
        WHEN number_of_reviews_ltm = 0 THEN '3. 沉寂（曾有评论，近一年无）'
        ELSE                                '2. 活跃（近一年有评论）'
    END                                                            AS 生命周期状态,

    CASE WHEN availability_365 > 0 THEN 'A. 仍在接客'
         ELSE                           'B. 已停止接客' END       AS 接客状态,

    COUNT(*)                                                       AS 房源数

FROM listings
GROUP BY 生命周期状态, 接客状态
ORDER BY 生命周期状态, 接客状态;
