-- 拆解「超级房东」：93 个管 20 套以上的房东，他们到底什么情况？
--
-- 业务问题
--     上一查询发现：房东规模维度上，零评论率呈 U 型 ——
--         个体房东（1套）71.9%，职业房东（20套以上）70.2%，中间两档只有 54%。
--     但「职业房东」那组只有 93 个人、6,522 套房源，人均 70 套。
--     少数人的行为可能被放大成一类人的特征，必须拆开看。
--
-- 要回答的问题
--     1. 这 93 人里，是所有人都差，还是差的人特别差？
--     2. 零评论房源是否集中在少数几个人手上？
--
-- 结论
--     ① 极度集中：前 10 位房东贡献了该组 51% 的零评论房源（2,338 / 4,576）
--     ② 榜首房东 107434423 一人挂 955 套（占全城 3.2%），其中 917 套零评论，
--        相当于全城所有零评论房源的 4.6% —— 一个人贡献了近 5% 的无效供给
--     ③ 93 人中 50 人（54%）零评论率超过 75%，但并非全都差：
--        2 人全部房源都有评论，1 人仅 12.9%
--     ④ 结论修正：不是「规模大就一定差」，而是「大部分超级房东在占位，
--        少数在认真经营」—— 规模化本身不是问题，经营意愿才是

SELECT
    host_id                                                        AS 房东ID,

    COUNT(*)                                                       AS 房源数,

    SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)     AS 零评论数,

    ROUND(
        100.0 * SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)
        / COUNT(*),
        1
    )                                                              AS 零评论率

FROM listings
WHERE calculated_host_listings_count >= 20      -- 只看超级房东
GROUP BY host_id
ORDER BY 房源数 DESC;
