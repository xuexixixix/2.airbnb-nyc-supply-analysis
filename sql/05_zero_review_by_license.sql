-- 按短租持证状态统计「零需求房源」的比例
--
-- 业务问题
--     前面三个维度测的是「房源长什么样」（在哪、什么类型、谁的）。
--     这个维度测的是另一回事 —— 房东有没有在【合规地做生意】。
--
-- 背景
--     纽约市对短租实行登记制：房东必须持执照，或符合豁免条件。
--     本快照中 82.5% 的房源【两者皆无】。
--
-- 🚨 口径修正（2026-10-06）
--     上句的「82.5% 两者皆无」曾被解读为「平台处于监管真空」—— 这是误读。
--     纽约法规管的是「30 天【以下】」的短租；30 天起租的长租型本来就不需要登记。
--     把长租型算进「无证」是口径错误。
--
--     仅统计短租型（minimum_nights < 30，n=5,540）时：
--         已豁免   2,905  52.4%
--         有执照   2,268  40.9%
--         无记录     367   6.6%   ← 只有 6.6% 真的没合规
--     → 真正的短租里 93.4% 要么持证、要么合规豁免，合规状况良好。
--     详见 sql/07_license_stratified.sql 与 sql/12_dimension_comparison.sql。
--
-- 假设
--     无记录（不合规）的房东，可能不敢认真投入运营，只是把房子挂着占位，
--     因此零评论率应该更高。
--     如果成立 → 支撑「监管套利」这条叙事。
--
-- 字段取值（先查过再写的，不是猜的）
--     NULL            24,973 条   真正没有值
--     'Exempt'         2,956 条   豁免
--     'OSE-STRREG-…'   2,330 条   真实执照号（值唯一，无法逐一列举）
--
-- ⚠️ 为什么用【排除法】写 CASE WHEN
--     执照号有 2000 多个不同的值，没法一条条写进 WHEN。
--     而 CASE WHEN 是【从上往下匹配，命中即停】——
--     所以只要把最特殊的两种情况先排除掉，剩下的 ELSE 自然就是「有执照」。
--        先排除 NULL  → 再排除 Exempt → 剩下的全部归入"有执照"
--
-- 结论
--     这是全部四个维度中【差异最大】的一个。
--
--     持证状态           总房源     零评论率
--     1. 无记录（不合规）  24,973     73.9%
--     2. 已豁免            2,956     39.6%
--     3. 有执照            2,330      6.6%
--
--     极差 67.3 个百分点，远超前三个维度：
--         房型 1.3 ／ 地理 5.3 ／ 房东规模 18.3 ／ 持证 67.3
--
--     有执照的房源中，93.4% 在过去一年都有评论 —— 基本都在正常经营。
--
--     ⚠️ 混淆因素检验（已做）
--         持证房源的房型分布确实不同（75.2% 是独立间，因纽约法规要求房东在场）。
--         但在【同一房型内部】再比一次，差异依然成立：
--             整租   无记录 72.0%  vs  有执照 3.7%   差 68.3
--             独立间 无记录 76.7%  vs  有执照 7.5%   差 69.2
--         两次差异几乎相同 → 房型不是解释变量，持证状态是独立信号。
--
--     ⚠️ 因果关系不可反推
--         持证不是"经营好"的原因，而是"房东在认真做生意"的【标记】。
--         原因与结果不可颠倒。
--
--     ❓ 待查：「Exempt（豁免）」的判定标准未确认，需查纽约市法规原文。
--         该组特征异常：平均挂牌价 610 元（是无记录的 2.7 倍），
--         且组内整租 13.9% 与独立间 48.6% 差异极大。

SELECT
    CASE
        -- SQL 里判断"没有值"必须用 IS NULL，不能写 = NULL
        -- （NULL 的含义是"未知"，用一个未知去等于另一个未知，结果还是未知）
        WHEN license IS NULL      THEN '1. 无记录（不合规）'

        WHEN license = 'Exempt'   THEN '2. 已豁免'

        -- 上面两个都没命中 → 剩下的一定是真实执照号
        ELSE                           '3. 有执照'

    END                                                            AS 持证状态,

    COUNT(*)                                                       AS 总房源数,

    SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)     AS 零评论房源数,

    ROUND(
        100.0 * SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)
        / COUNT(*),
        1
    )                                                              AS 零评论率百分比

FROM listings
GROUP BY 持证状态
ORDER BY 持证状态;
