-- 修正：持证效应的分层检验 —— 原来的 67.3 个百分点大部分是假的
--
-- 背景
--     05_zero_review_by_license.sql 算出：
--         无记录 73.9%  vs  有执照 6.6%   极差 67.3 个百分点
--     看起来是全部四个维度中最强的信号。但这个数字有问题。
--
-- 第一次怀疑：房型是不是混淆因素？
--     纽约法规要求「房东必须在场」，持证房源应多为独立间而非整租。
--     实测证实：持证房源 75.2% 是独立间，无记录房源只有 38.9%。
--     → 但分层检验（整租内 / 独立间内分别比）后，差异依然成立：
--           整租   无记录 72.0%  vs  有执照 3.7%   差 68.3
--           独立间 无记录 76.7%  vs  有执照 7.5%   差 69.2
--       两次差异几乎相同 → 房型不是解释变量。（此步见 05 的结论注释）
--
-- 第二次怀疑（本文件）：长租/短租是不是混淆因素？
--     06 已发现：无记录房源 98.5% 是长租型，有执照房源 97.4% 是短租型。
--     持证状态与「长租/短租」几乎完全绑定 —— 这才是真正的大问题。
--
-- 结论（本查询的分层结果）
--     短租型（真正的短租）内部分层：
--         无记录     368 套   29.6%
--         已豁免   2,905 套   38.9%
--         有执照   2,269 套    5.2%    ← 仍然最低
--
--     长租型内部分层：
--         无记录  24,605 套   74.6%
--         已豁免      51 套   84.3%
--         有执照      61 套   57.4%
--
--     对比：
--         不分层   73.9%  vs  6.6%    →  67.3 pp
--         短租型内 29.6%  vs  5.2%    →  24.4 pp
--
--     ⚠️ 67.3 → 24.4，缩水 64%。
--        原因：之前是把两种不同的商品混在一起比。
--        持证确实有效应（24.4 个百分点仍然显著），但没有原来那么夸张。
--
--     这个现象叫【成分效应】—— 差异可能全部来自「两组人的组成不同」，
--     而不是你以为的那个变量。看到大差异先问一句：是不是把两种东西混在一起比了。

SELECT
    -- 第一层：长租 / 短租
    CASE WHEN minimum_nights >= 30 THEN '长租型' ELSE '短租型' END AS 类型,

    -- 第二层：持证状态
    CASE WHEN license IS NULL      THEN '1. 无记录'
         WHEN license = 'Exempt'   THEN '2. 已豁免'
         ELSE                           '3. 有执照' END         AS 持证状态,

    COUNT(*)                                                       AS 房源数,

    SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)     AS 零评论房源数,

    ROUND(
        100.0 * SUM(CASE WHEN number_of_reviews_ltm = 0 THEN 1 ELSE 0 END)
        / COUNT(*), 1
    )                                                              AS 零评论率

FROM listings
GROUP BY 类型, 持证状态
ORDER BY 类型, 持证状态;
