-- 平台供给总览：把全部房源按「活跃度」切成四类
--
-- 业务问题
--     平台上有 30,259 套「房源」，但挂牌 ≠ 有效供给。
--     这些房源里，有多少是真的在做生意的？
--
-- 方法
--     用两个维度交叉分类：
--       ① 过去一年有没有评论（number_of_reviews_ltm）
--          —— 判断「过去有没有生意」
--       ② 未来能不能被预订（availability_365 > 0）
--          —— 判断「现在愿不愿意接客」
--
--     ⚠️ 为什么用「有没有评论」而不是「有没有订单」
--         平台不公开订单数据。Inside Airbnb 官方用评论数反推出租率，
--         我们已实测确认 estimated_occupancy_l365d 与 number_of_reviews_ltm
--         完全等价（两者为 0 的行 100% 重合，详见 scripts/01_verify_metrics.py）。
--         因此「零评论」不等于「零订单」，只能表述为「需求极低」。
--         （按 50% 评论率估算：1 笔订单有 50% 概率零评论，5 笔订单降到 3.1%）
--
-- 结论
--     四类房源分布如下：
--         A 有评论 + 可订     10,136   33.5%   正常经营
--         B 有评论 + 不可订      340    1.1%   暂时歇业
--         C 零评论 + 不可订    6,451   21.3%   死房源（已放弃）
--         D 零评论 + 仍可订   13,332   44.1%   ← 开门但没客
--
--     D 类是平台的真实问题：开放预订、整年没有一条评论，
--     占着展示位与搜索排名，却不产生任何 GMV。
--
--     ⚠️ 后续修正（见 06_minimum_nights_structure.sql）
--         本查询把「长租型（最短入住 30 天以上）」和「短租型」混在一起统计。
--         实测：平台上 81.7% 的房源其实是长租型，与短租不是同一种商品。
--         把两者分开后，真正的短租只有 5,542 套，且经营状况良好。
--         → 本表的 D 类数字需要用 06 的口径重新理解。

SELECT
    -- 两个维度交叉，切成四格
    CASE WHEN number_of_reviews_ltm = 0 THEN '零评论' ELSE '有评论' END AS 评论状态,

    CASE WHEN availability_365 > 0     THEN '可订'   ELSE '不可订' END AS 可订状态,

    COUNT(*)                                                       AS 房源数,

    ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM listings), 1)   AS 占全部房源百分比

FROM listings
GROUP BY 评论状态, 可订状态
ORDER BY 房源数 DESC;
